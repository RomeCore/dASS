namespace LLMDesktopAssistant.Styles.Theming
{
	/// <summary>
	/// The theme variant the user asked for.
	/// </summary>
	public enum ThemeMode
	{
		/// <summary>
		/// Follow the operating system preference.
		/// </summary>
		System,

		/// <summary>
		/// Always use the light variant.
		/// </summary>
		Light,

		/// <summary>
		/// Always use the dark variant.
		/// </summary>
		Dark,
	}
}
