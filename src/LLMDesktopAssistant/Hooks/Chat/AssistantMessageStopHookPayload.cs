namespace LLMDesktopAssistant.Hooks.Chat
{
	/// <summary>
	/// The document a <c>message.assistant.stop.*</c> hook receives: what the message ended with.
	/// </summary>
	/// <remarks>
	/// The status is repeated from the event name because a hook that matches the whole family
	/// (<c>message.assistant.stop.*</c>) needs it in the document. A message that never reached a terminal status - the
	/// prompt could not be built, the request could not be sent - is reported as <c>error</c>, or as <c>cancelled</c>
	/// when the turn was cancelled.
	/// </remarks>
	public sealed class AssistantMessageStopHookPayload
	{
		/// <summary>
		/// The chat the message belongs to, or <see langword="null"/> when the world has none.
		/// </summary>
		public int? ChatId { get; init; }

		/// <summary>
		/// The database id of the message.
		/// </summary>
		public int? MessageId { get; init; }

		/// <summary>
		/// The 1-based index of the message in the history.
		/// </summary>
		public int? Index { get; init; }

		/// <summary>
		/// The id of the agent that answered.
		/// </summary>
		public Guid AgentId { get; init; }

		/// <summary>
		/// The name of the agent that answered.
		/// </summary>
		public string Agent { get; init; } = string.Empty;

		/// <summary>
		/// The id of the execution stage the agent ran in.
		/// </summary>
		public Guid StageId { get; init; }

		/// <summary>
		/// The zero-based cycle of this agent that produced the message.
		/// </summary>
		public int Cycle { get; init; }

		/// <summary>
		/// The reported status in kebab case: <c>success</c>, <c>error</c> or <c>cancelled</c>.
		/// </summary>
		public string Status { get; init; } = string.Empty;

		/// <summary>
		/// The text the message ended with, possibly empty.
		/// </summary>
		public string Content { get; init; } = string.Empty;

		/// <summary>
		/// The tool calls the message carries, or <see langword="null"/> when it carries none.
		/// </summary>
		public ToolCallInfo[]? ToolCalls { get; init; }

		/// <summary>
		/// The usage of the request, or <see langword="null"/> when the model reported none.
		/// </summary>
		public UsageInfo? Usage { get; init; }

		/// <summary>
		/// The rendered error text, or <see langword="null"/> when the message has no error.
		/// </summary>
		public string? Error { get; init; }

		/// <summary>
		/// Whether the assistant message identifies itself as a user, or <see langword="null"/> when the agent declares
		/// nothing.
		/// </summary>
		public bool? IsUserLike { get; init; }

		/// <summary>
		/// One tool call the message carries.
		/// </summary>
		public sealed class ToolCallInfo
		{
			/// <summary>
			/// The bare tool name, for example <c>fs-edit</c>.
			/// </summary>
			public string Name { get; init; } = string.Empty;

			/// <summary>
			/// The terminal status of the call in kebab case, for example <c>completed</c>.
			/// </summary>
			public string Status { get; init; } = string.Empty;
		}

		/// <summary>
		/// What the request cost.
		/// </summary>
		public sealed class UsageInfo
		{
			/// <summary>
			/// The model that produced the message.
			/// </summary>
			public string Model { get; init; } = string.Empty;

			/// <summary>
			/// The tokens sent to the model as input, or <see langword="null"/> when unknown.
			/// </summary>
			public int? InputTokens { get; init; }

			/// <summary>
			/// The input tokens written to the prompt cache, or <see langword="null"/> when the provider has none.
			/// </summary>
			public int? CacheCreateTokens { get; init; }

			/// <summary>
			/// The input tokens served from the prompt cache, or <see langword="null"/> when the provider has none.
			/// </summary>
			public int? InputCacheHitTokens { get; init; }

			/// <summary>
			/// The input tokens that missed the prompt cache, or <see langword="null"/> when the provider has none.
			/// </summary>
			public int? InputCacheMissTokens { get; init; }

			/// <summary>
			/// The tokens generated by the model, or <see langword="null"/> when unknown.
			/// </summary>
			public int? OutputTokens { get; init; }

			/// <summary>
			/// The seconds until the first output token arrived.
			/// </summary>
			public double TimeToFirstToken { get; init; }

			/// <summary>
			/// The seconds spent generating the message.
			/// </summary>
			public double GenerationTime { get; init; }
		}
	}
}
