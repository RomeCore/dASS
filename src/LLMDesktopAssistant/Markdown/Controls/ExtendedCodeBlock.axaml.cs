	/// <summary>
	/// One fenced code block: the top bar (language, tabs, split and actions), the source with syntax highlighting,
	/// and the preview pane next to it in split view.
	/// </summary>
	/// <remarks>
	/// The control owns its state; the node only hands it the providers and the content. The <see cref="CodeBlock"/>
	/// inside is a plain text renderer - the chrome, the tabs and the splitter all live here.
	/// </remarks>
	public partial class ExtendedCodeBlock : UserControl
	{
		private ExtendedCodeBlockViewModel? _viewModel;

		/// <summary>
		/// The markdig block of the current parse. Markdig rebuilds its AST on every parse, so the block handed to
		/// <see cref="Update"/> must be the one the context reads - a captured first block would go stale.
		/// </summary>
		private FencedCodeBlock? _block;

		/// <summary>
		/// Defines the <see cref="AutoSyntaxHighlight"/> property.
		/// </summary>
		public static readonly StyledProperty<bool> AutoSyntaxHighlightProperty =
			AvaloniaProperty.Register<ExtendedCodeBlock, bool>(nameof(AutoSyntaxHighlight), true);

		/// <summary>
		/// Gets or sets a value indicating whether to automatically apply syntax highlighting when the code or language changes.
		/// </summary>
		public bool AutoSyntaxHighlight
		{
			get => GetValue(AutoSyntaxHighlightProperty);
			set => SetValue(AutoSyntaxHighlightProperty, value);
		}

		/// <summary>
		/// Defines the <see cref="Language"/> property.
		/// </summary>
		public static readonly StyledProperty<string?> LanguageProperty =
			AvaloniaProperty.Register<ExtendedCodeBlock, string?>(nameof(Language));

		/// <summary>
		/// Gets or sets the programming language of the code block.
		/// </summary>
		public string? Language
		{
			get => GetValue(LanguageProperty);
			set => SetValue(LanguageProperty, value);
		}

		/// <summary>
		/// Defines the <see cref="ColorTheme"/> property.
		/// </summary>
		public static readonly StyledProperty<ThemeName> ColorThemeProperty =
			AvaloniaProperty.Register<ExtendedCodeBlock, ThemeName>(
				nameof(ColorTheme),
				ThemeName.DarkPlus,
				inherits: true);

		/// <summary>
		/// Gets or sets the theme used for syntax highlighting.
		/// The value is inherited from an ancestor, so <see cref="MarkdownRenderer.CodeBlockColorTheme"/>
		/// can configure all code blocks generated by a renderer.
		/// </summary>
		public ThemeName ColorTheme
		{
			get => GetValue(ColorThemeProperty);
			set => SetValue(ColorThemeProperty, value);
		}

		/// <summary>
		/// Defines the <see cref="CustomColorTheme"/> property.
		/// </summary>
		public static readonly StyledProperty<string?> CustomColorThemeProperty =
			AvaloniaProperty.Register<ExtendedCodeBlock, string?>(
				nameof(CustomColorTheme),
				inherits: true);

		/// <summary>
		/// Gets or sets the name of a theme registered with <see cref="SyntaxHighlighting.RegisterCustomTheme"/>.
		/// When not set, <see cref="ColorTheme"/> is used.
		/// The value is inherited from an ancestor, so <see cref="MarkdownRenderer.CodeBlockCustomColorTheme"/>
		/// can configure all code blocks generated by a renderer.
		/// </summary>
		public string? CustomColorTheme
		{
			get => GetValue(CustomColorThemeProperty);
			set => SetValue(CustomColorThemeProperty, value);
		}

		/// <summary>
		/// Backing field for the <see cref="Code"/> property.
		/// </summary>
		public static readonly DirectProperty<ExtendedCodeBlock, string?> CodeProperty =
			AvaloniaProperty.RegisterDirect<ExtendedCodeBlock, string?>(
				nameof(Code),
				o => o.Code,
				(o, v) => o.Code = v);

		/// <summary>
		/// Defines the <see cref="IsCodeWrapped"/> property.
		/// </summary>
		public static readonly StyledProperty<bool> IsCodeWrappedProperty =
			AvaloniaProperty.Register<ExtendedCodeBlock, bool>(nameof(IsCodeWrapped), true);

		/// <summary>
		/// Gets or sets a value indicating whether the code content is wrapped.
		/// </summary>
		public bool IsCodeWrapped
		{
			get => GetValue(IsCodeWrappedProperty);
			set => SetValue(IsCodeWrappedProperty, value);
		}

		/// <summary>
		/// Defines the <see cref="TextWrapping"/> property.
		/// </summary>
		public static readonly DirectProperty<ExtendedCodeBlock, TextWrapping> TextWrappingProperty =
			AvaloniaProperty.RegisterDirect<ExtendedCodeBlock, TextWrapping>(
				nameof(TextWrapping),
				o => o.TextWrapping);

		/// <summary>
		/// Gets the text wrapping mode currently used by the code block.
		/// </summary>
		public TextWrapping TextWrapping =>
			IsCodeWrapped ? TextWrapping.Wrap : TextWrapping.NoWrap;

		/// <summary>
		/// Defines the <see cref="HorizontalScrollBarVisibility"/> property.
		/// </summary>
		public static readonly DirectProperty<ExtendedCodeBlock, ScrollBarVisibility> HorizontalScrollBarVisibilityProperty =
			AvaloniaProperty.RegisterDirect<ExtendedCodeBlock, ScrollBarVisibility>(
				nameof(HorizontalScrollBarVisibility),
				o => o.HorizontalScrollBarVisibility);

		/// <summary>
		/// Gets the horizontal scroll bar visibility currently used by the code block.
		/// </summary>
		public ScrollBarVisibility HorizontalScrollBarVisibility =>
			IsCodeWrapped ? ScrollBarVisibility.Disabled : ScrollBarVisibility.Auto;

		private string? _code = string.Empty;

		/// <summary>
		/// An alternative property of <see cref="Inlines"/> to set the code content and apply syntax highlighting automatically.
		/// </summary>
		/// <remarks>
		/// Every assignment rebuilds the inline collection from scratch instead of clearing the one the text block
		/// already owns: <see cref="InlineCollection.Add(string)"/> appends to the owning text block's
		/// <c>Text</c> and that text is not touched by <c>Clear()</c>, so appending into a live collection grows the
		/// visible source by the whole block on every streaming update.
		/// </remarks>
		public string? Code
		{
			get => _code;
			set
			{
				if (!SetAndRaise(CodeProperty, ref _code, value)) return;
				RebuildInlines();
			}
		}

		private InlineCollection _inlines = [];

		/// <summary>
		/// Gets the inline collection containing the code content.
		/// </summary>
		public InlineCollection Inlines => _inlines;

		/// <summary>
		/// Gets or sets the Markdown source span represented by the code text layout.
		/// The value is retained until the template text block is available.
		/// </summary>
		public SourceSpan SourceSpan
		{
			get;
			set
			{
				field = value;
				SourceTextBlock.SetPropertyValue(nameof(SourceSpan), value);
			}
		}

		private bool isApplyingSyntaxHighlighting; // prevent re-entrance

		/// <summary>
		/// Initializes the control.
		/// </summary>
		public ExtendedCodeBlock()
		{
			InitializeComponent();

			SourceTextBlock.Inlines = _inlines;
			SourceTextBlock.SetPropertyValue(nameof(SourceSpan), SourceSpan);
		}

		/// <summary>
		/// Builds a fresh inline collection for <see cref="Code"/> and hands it to the text block.
		/// </summary>
		private void RebuildInlines()
		{
			var inlines = new InlineCollection();

			if (!string.IsNullOrEmpty(_code))
			{
				var lines = _code.Split(["\r\n", "\r", "\n"], StringSplitOptions.None);
				for (var i = 0; i < lines.Length; i++)
				{
					inlines.Add(new Run(lines[i]));
					if (i < lines.Length - 1) inlines.Add(new LineBreak());
				}
			}

			_inlines = inlines;

			// The text block keeps the previous plain text separate from its inlines, so it has to be dropped too.
			SourceTextBlock.Text = null;
			SourceTextBlock.Inlines = inlines;

			if (AutoSyntaxHighlight) HighlightSyntax();
		}

		/// <summary>
		/// Called when an Avalonia property on the control changes.
		/// </summary>
		/// <param name="change">Details about the property change.</param>
		protected override void OnPropertyChanged(AvaloniaPropertyChangedEventArgs change)
		{
			base.OnPropertyChanged(change);

			if (change.Property == LanguageProperty)
			{
				if (AutoSyntaxHighlight) RebuildInlines();
			}
			else if (change.Property == ColorThemeProperty)
			{
				if (AutoSyntaxHighlight) RebuildInlines();
			}
			else if (change.Property == CustomColorThemeProperty)
			{
				if (AutoSyntaxHighlight) RebuildInlines();
			}
			else if (change.Property == IsCodeWrappedProperty)
			{
				var isCodeWrapped = change.NewValue is true;

				var (textWrappingOldValue, textWrappingNewValue) = isCodeWrapped ?
					(TextWrapping.NoWrap, TextWrapping.Wrap) :
					(TextWrapping.Wrap, TextWrapping.NoWrap);
				RaisePropertyChanged(TextWrappingProperty, textWrappingOldValue, textWrappingNewValue);

				var (scrollBarVisibilityOldValue, scrollBarVisibilityNewValue) = isCodeWrapped ?
					(ScrollBarVisibility.Auto, ScrollBarVisibility.Disabled) :
					(ScrollBarVisibility.Disabled, ScrollBarVisibility.Auto);
				RaisePropertyChanged(HorizontalScrollBarVisibilityProperty, scrollBarVisibilityOldValue, scrollBarVisibilityNewValue);

				if (SourceScrollViewer is not null && SourceTextBlock is not null)
				{
					SourceTextBlock.Width = SourceScrollViewer.Viewport.Width;
					SourceTextBlock.UpdateLayout(); // fix bug that the text block does not resize correctly
					SourceTextBlock.Width = double.NaN;
				}
			}
		}

		/// <summary>
		/// Applies syntax highlighting to the code block based on the specified language.
		/// </summary>
		public void HighlightSyntax()
		{
			if (isApplyingSyntaxHighlighting) return;
			if (string.IsNullOrWhiteSpace(Language) || Inlines.Count == 0) return;

			isApplyingSyntaxHighlighting = true;
			try
			{
				SyntaxHighlighting.Create(Language.ToLower()).FormatInlines(Inlines, ColorTheme, CustomColorTheme);
			}
			finally
			{
				isApplyingSyntaxHighlighting = false;
			}
		}

		/// <summary>
		/// Creates the state from the document the block belongs to. Called by the node before the first update.
		/// </summary>
		public void Initialize(
			FencedCodeBlock block,
			MarkdownRenderer renderer,
			object? owner,
			bool isCompact)
		{
			_block = block;

			_viewModel = new ExtendedCodeBlockViewModel(
				this,
				isCompact,
				// Resolved lazily: the node is created while the document is being parsed, long before the consumer's
				// binding has put the provider lists onto the renderer.
				() => renderer.GetValue(MarkdownControl.CodeBlockPreviewProvidersProperty),
				() => renderer.GetValue(MarkdownControl.CodeBlockActionProvidersProperty),
				() => CreateContext(renderer, owner),
				() => !MarkdownControl.GetIsStreaming(renderer));
			UpdateSplitColumns();

			_viewModel.PropertyChanged += ViewModel_PropertyChanged;

			// The provider lists arrive from the consumer as bindings, which may land after the document has already
			// been parsed - including long after the last update for a message loaded from history.
			renderer.PropertyChanged += Renderer_PropertyChanged;

			DataContext = _viewModel;
		}

		private void Renderer_PropertyChanged(object? sender, AvaloniaPropertyChangedEventArgs e)
		{
			if (e.Property != MarkdownControl.CodeBlockPreviewProvidersProperty
				&& e.Property != MarkdownControl.CodeBlockActionProvidersProperty)
			{
				return;
			}

			_viewModel?.EnsureCreated();
			_viewModel?.Update(isFinal: false);
		}


		private void ViewModel_PropertyChanged(object? sender, System.ComponentModel.PropertyChangedEventArgs e)
		{
			if (e.PropertyName is nameof(ExtendedCodeBlockViewModel.IsSplit))
				UpdateSplitColumns();
		}

		private bool _prevIsSplit = false;
		private void UpdateSplitColumns()
		{
			var isSplit = _viewModel!.IsSplit;
			if (_prevIsSplit != isSplit)
			{
				_prevIsSplit = isSplit;
				if (isSplit)
				{
					ContentGrid.ColumnDefinitions = [
						new ColumnDefinition(GridLength.Star),
						new ColumnDefinition(GridLength.Auto),
						new ColumnDefinition(GridLength.Star)
					];
					Grid.SetColumn(ContentGrid_SourcePart, 0);
					Grid.SetColumn(ContentGrid_SplitterPart, 1);
					Grid.SetColumn(ContentGrid_PreviewPart, 2);
				}
				else
				{
					Grid.SetColumn(ContentGrid_SourcePart, 0);
					Grid.SetColumn(ContentGrid_SplitterPart, 0);
					Grid.SetColumn(ContentGrid_PreviewPart, 0);
					ContentGrid.ColumnDefinitions = [new ColumnDefinition(GridLength.Star)];
				}
			}
		}

		private MarkdownCodeBlockContext CreateContext(MarkdownRenderer renderer, object? owner)
		{
			var block = _block;
			var (language, info) = block is null ? (null, null) : GetLanguageAndInfo(block);

			return new MarkdownCodeBlockContext
			{
				Content = new CodeBlockContent(
					language ?? string.Empty,
					block is null ? string.Empty : GetText(block),
					info ?? string.Empty,
					default),
				Renderer = renderer,
				MarkdownOwner = owner,
			};
		}

		/// <summary>
		/// Applies one content update: the language, the source text, and whether the block is final.
		/// </summary>
		public void Update(FencedCodeBlock block, bool ensureCreated, bool isFinal)
		{
			if (_viewModel is null) return;

			_block = block;

			var (language, _) = GetLanguageAndInfo(block);
			Language = language;
			Code = GetText(block);

			if (ensureCreated) _viewModel.EnsureCreated();
			_viewModel.Update(isFinal);
		}

		private static (string? Language, string? Info) GetLanguageAndInfo(FencedCodeBlock block)
		{
			var info = block.Info?.Trim();
			var language = info?.Split(' ', '|', '#').FirstOrDefault();
			return (language, info);
		}

		private static string GetText(FencedCodeBlock block)
		{
			var lines = block.Lines;
			if (lines.Lines is null) return string.Empty;

			return string.Join('\n', lines.Lines.Take(lines.Count).Select(line => line.Slice.ToString()));
		}
	}
}
